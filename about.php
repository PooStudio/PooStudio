  <script>
    const journey = {
      held: 0,
      states: ['waiting at the threshold', 'remembering what was real', 'feeling the weight', 'choosing yourself']
    };

    function buildMemoryChoices() {
      document.querySelectorAll('.chapter').forEach((chapter, index) => {
        const choices = document.createElement('div');
        choices.className = 'memory-choice';
        choices.innerHTML = '<span class="memory-choice-label">how do you carry this?</span><button type="button" data-choice="hold">hold it</button><button type="button" data-choice="release">let it move</button>';
        chapter.appendChild(choices);
        choices.addEventListener('click', (event) => {
          const choice = event.target.closest('button');
          if (!choice || choice.disabled) return;
          journey.held = Math.max(journey.held, index + 1);
          document.getElementById('journey-count').textContent = journey.held;
          document.getElementById('journey-state').textContent = choice.dataset.choice === 'hold' ? journey.states[Math.min(index + 1, 3)] : 'making room to breathe';
          document.getElementById('journey-meter-fill').style.width = `${journey.held * 25}%`;
          choices.classList.add('answered', choice.dataset.choice);
          choices.querySelectorAll('button').forEach((button) => { button.disabled = true; });
          chapter.classList.add('memory-held');
        });
      });
    }

    function enter() {
      const gate = document.getElementById('gate');
      gate.style.transition = 'opacity 2s ease';
      gate.style.opacity = '0';
      setTimeout(() => {
        gate.style.display = 'none';
        document.getElementById('main').classList.add('visible');
        startHearts();
      }, 2000);
    }

    buildMemoryChoices();

    const loveHateSlider = document.getElementById('love-hate-slider');
    const loveHateCopy = document.getElementById('love-hate-copy');
    const loveHateReadout = document.getElementById('love-hate-readout');
    const loveHateMoments = [
      ['I hate what you did. I hate that you made me doubt my own heart.', 'anger has a memory'],
      ['I hate what you did. I still love who I thought you were.', 'the wound is still warm'],
      ['I miss you. I hate that I miss you. Both things are true.', 'two truths, one body'],
      ['I remember the good and resent it for surviving the bad.', 'nothing stays simple'],
      ['I still love you. That does not make what happened forgivable.', 'love is not permission']
    ];
    loveHateSlider.addEventListener('input', () => {
      const moment = loveHateMoments[Math.round(Number(loveHateSlider.value) / 25)];
      loveHateCopy.textContent = moment[0];
      loveHateReadout.textContent = moment[1];
      loveHateSlider.style.setProperty('--love-position', `${loveHateSlider.value}%`);
    });

    window.addEventListener('scroll', () => {
      const scrollTop = window.scrollY;
      const docHeight = document.documentElement.scrollHeight - window.innerHeight;
      const pct = (scrollTop / docHeight) * 100;
      document.getElementById('progress-line').style.width = pct + '%';
    });

    function startHearts() {
      const container = document.getElementById('float-hearts');
      const symbols = ['♡', '♥', '·', '∘'];
      setInterval(() => {
        const h = document.createElement('div');
        h.classList.add('fh');
        h.textContent = symbols[Math.floor(Math.random() * symbols.length)];
        h.style.left = Math.random() * 100 + 'vw';
        h.style.bottom = '-20px';
        h.style.fontSize = (0.6 + Math.random() * 0.8) + 'rem';
        const dur = 12 + Math.random() * 16;
        h.style.animationDuration = dur + 's';
        h.style.animationDelay = Math.random() * 3 + 's';
        container.appendChild(h);
        setTimeout(() => h.remove(), (dur + 4) * 1000);
      }, 1200);
    }

    const fadeObserver = new IntersectionObserver((entries) => {
      entries.forEach(e => {
        if (e.isIntersecting) {
          e.target.classList.add('in-view');
        }
      });
    }, { threshold: 0.12 });

    document.querySelectorAll('.fade-section').forEach(el => fadeObserver.observe(el));

    const finaleObserver = new IntersectionObserver((entries) => {
      entries.forEach(e => {
        if (e.isIntersecting) {
          e.target.querySelectorAll('.finale-word, .finale-divider, .finale-line, .last-note')
            .forEach(el => el.classList.add('revealed'));
        }
      });
    }, { threshold: 0.2 });

    const finale = document.getElementById('finale');
    if (finale) finaleObserver.observe(finale);

    document.addEventListener('DOMContentLoaded', () => {
    });
  </script>
